#string slicing means taking a specific part (substring) of a string by using its indexing.
name = "Maryam"
print(name[0:6])

language = "python"
print(language[0:4:2])
print(language[1:3])
print(len(language))

word = "ABCDEF"
print(word[3:5])

country = "pakistan"
print(country[0:4])
print(country[0:5:2])
print(country[-3:])
print(country[-5:-1])

text = "I love python"
print(text[7:13])
print(len(text))